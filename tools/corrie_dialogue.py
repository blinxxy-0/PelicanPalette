"""Writes the Corrie twins' approved everyday dialogue and gift tastes into the dev pack from
docs/corrie_twins_dialogue.md (its tables are the source: edit the doc, rerun this):
data/opal_dialogue.json, data/jet_dialogue.json, the gift tastes, schedule Loads and
Exhibition Hall days in data/opal.json and data/jet.json, and the i18n keys opal.dialogue.*, opal.gift.*, jet.dialogue.*, jet.gift.*.

Usage: python tools/corrie_dialogue.py"""
import json, re

PACK = "[CP] Gilded Vale (dev)"
GIFTS = {"Refined Quartz": "(O)338", "Fairy Rose": "(O)595", "Prismatic Shard": "(O)74", "Jade": "(O)70",
         "Triple Shot Espresso": "(O)253"}
TASTES = {
    "OpalCorrie": {"love": "338 82 74 595 221", "like": "-2 -12 -80", "dislike": "167", "hate": "168 747 172"},
    "JetCorrie": {"love": "338 82 74 253 70", "like": "-2 -12 198 202 213 214 219 227 228 728 730",
                  "dislike": "167 92 724 725 726", "hate": "168 747 172"},
}
WHO = {"opal": ("OpalCorrie", "Opal"), "jet": ("JetCorrie", "Jet")}
# Two days a week at the Exhibition Hall once Lupini's 8-heart event reopens it (the mail flag
# blinxxy.MuseArt_ValeHallOpen): outside its front, at its windows, Opal at the right-hand ones,
# Jet at the left (his dawn walk first). Rain keeps them in: rain comes before the weekdays.
_S2, _V = "blinxxy.MuseArt_ValeStudio2", "blinxxy.MuseArt_GildedVale"
HALL_DAYS = {
    "OpalCorrie": {d: f"900 {_V} 48 40 0/1700 blinxxy.MuseArt_ValeHouse 17 25 1/2200 {_S2} 3 6 2" for d in ("Tue", "Thu")},
    "JetCorrie": {d: f"600 {_V} 19 37 3/900 {_V} 40 40 0/1700 {_S2} 16 5 0/2100 {_S2} 18 6 2" for d in ("Tue", "Thu")},
}


def tables():
    doc = open("docs/corrie_twins_dialogue.md", encoding="utf-8").read()
    out = {}
    for slug, (_, title) in WHO.items():
        part = doc.split(f"\n## {title}\n", 1)[1].split("\n## ", 1)[0]
        rows = [r for r in part.splitlines() if r.startswith("| ") and not r.startswith("| Key") and not r.startswith("|---")]
        out[slug] = [tuple(c.strip() for c in r.strip("|").split(" | ", 1)) for r in rows]
    return out


def key_of(label):
    m = re.match(r"Gift: (.+)", label)
    if m:
        return "AcceptGift_" + GIFTS[m.group(1)]
    return {"Birthday gift, liked": "AcceptBirthdayGift_Positive", "Birthday gift, not liked": "AcceptBirthdayGift_Negative",
            "Gift, loved": "gift.love", "Gift, liked": "gift.like", "Gift, disliked": "gift.dislike",
            "Gift, hated": "gift.hate", "Gift, neutral": "gift.neutral"}.get(label, label.split(" (")[0])


def main():
    i18n_lines = []
    for slug, rows in tables().items():
        name, title = WHO[slug]
        when = {"ValeResidents": "true", f"HasFile:assets/{slug}/sprites.png": "true", f"HasFile:assets/{slug}/portraits.png": "true"}
        entries = {}
        for label, line in rows:
            k = key_of(label)
            ik = f"{slug}.{k}" if k.startswith("gift.") else f"{slug}.dialogue.{k.replace('(O)', '')}"
            i18n_lines.append((ik, line))
            if not k.startswith("gift.") and k != "rainy":
                entries[k] = f"{{{{i18n:{ik}}}}}"
        changes = [
            {"Action": "Load", "Target": f"Characters/Dialogue/{name}", "FromFile": "data/blank.json", "When": when},
            {"Action": "EditData", "Target": f"Characters/Dialogue/{name}", "When": when, "Entries": entries},
            {"Action": "EditData", "Target": "Characters/Dialogue/rainy", "When": when,
             "Entries": {name: f"{{{{i18n:{slug}.dialogue.rainy}}}}"}}]
        head = (f"// {name}'s everyday dialogue (1.4), batch 1, approved by the user 2026-11-09: generated by\n"
                f"// tools/corrie_dialogue.py from docs/corrie_twins_dialogue.md (edit the doc, rerun that).\n"
                f"// Keys as vanilla's: day names with heart levels, seasons, first days, the birthday\n"
                f"// (summer_2), rain, gifts. Portraits: $0 neutral, $h happy, $s sad, $u unique, $l touched, $a angry.\n")
        with open(f"{PACK}/data/{slug}_dialogue.json", "w", encoding="utf-8", newline="\n") as f:
            f.write(head + json.dumps({"Changes": changes}, indent=2, ensure_ascii=False) + "\n")
        # gift tastes in <slug>.json (replaced whole each run)
        path = f"{PACK}/data/{slug}.json"
        s = open(path, encoding="utf-8").read()
        # (a rerun: take out the gifts and the Include this wrote last time, and the comma before them)
        s = re.sub(r",\n    // ---- Gifts.*?// ---- What \w+ says ----\n    \{ \"Action\": \"Include\", \"FromFile\": \"data/\w+_dialogue.json\" \}\n", "\n", s, flags=re.S)
        t = TASTES[name]
        gifts = (f'\n    // ---- Gifts: love / like / dislike / hate / neutral (docs/corrie_twins_dialogue.md) ----\n'
                 f'    // Paintings: the mod\'s rule; an art lover (data/residents.json).\n'
                 f'    {{\n      "Action": "EditData",\n      "Target": "Data/NPCGiftTastes",\n      "When": {json.dumps(when)},\n'
                 f'      "Entries": {{ "{name}": "{{{{i18n:{slug}.gift.love}}}}/{t["love"]}/{{{{i18n:{slug}.gift.like}}}}/{t["like"]}/'
                 f'{{{{i18n:{slug}.gift.dislike}}}}/{t["dislike"]}/{{{{i18n:{slug}.gift.hate}}}}/{t["hate"]}/{{{{i18n:{slug}.gift.neutral}}}}/" }}\n    }},\n'
                 f'    // ---- {"Her" if slug == "opal" else "His"} days (data/{slug}_schedule.json), and the Exhibition Hall days once it reopens ----\n'
                 f'    {{ "Action": "Load", "Target": "Characters/schedules/{name}", "FromFile": "data/{slug}_schedule.json", "When": {json.dumps(when)} }},\n'
                 f'    {{\n      "Action": "EditData",\n      "Target": "Characters/schedules/{name}",\n'
                 f'      "When": {json.dumps({**when, "HasFlag": "blinxxy.MuseArt_ValeHallOpen"})},\n'
                 f'      "Entries": {json.dumps(HALL_DAYS[name])}\n    }},\n'
                 f'    // ---- What {"she" if slug == "opal" else "he"} says ----\n'
                 f'    {{ "Action": "Include", "FromFile": "data/{slug}_dialogue.json" }}\n')
        anchor = f'    {{ "Action": "Load", "Target": "Portraits/{name}", "FromFile": "assets/{slug}/portraits.png", "When": {json.dumps(when)} }}'
        assert anchor in s, anchor
        s = s.replace(anchor, anchor + "," + gifts.rstrip("\n").rstrip(",") if False else anchor + ",\n" + gifts.lstrip("\n").rstrip("\n"), 1)
        s = s.replace("    // Gift tastes, the schedule and dialogue come with the writing (each batch approved first).\n", "")
        s = s.replace("// Gift tastes, the schedule and dialogue come with the writing (each batch approved first).\n", "")
        open(path, "w", encoding="utf-8", newline="\n").write(s)
    # i18n: replace any earlier opal.dialogue/gift and jet.* lines, insert after jet.name
    p = f"{PACK}/i18n/default.json"
    s = open(p, encoding="utf-8").read()
    s = re.sub(r'  "(opal|jet)\.(dialogue\.[^"]+|gift\.[a-z]+)": .*\n', "", s)
    block = "".join(f"  {json.dumps(k)}: {json.dumps(v, ensure_ascii=False)},\n" for k, v in i18n_lines)
    anchor = '  "jet.name": "Jet",\n'
    s = s.replace(anchor, anchor + block, 1)
    open(p, "w", encoding="utf-8", newline="\n").write(s)
    print("wrote", len(i18n_lines), "lines")


if __name__ == "__main__":
    main()
