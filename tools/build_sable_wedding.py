"""Writes Sable's wedding ([CP] Pelican Palette/data/sable_wedding.json).

The game's wedding script picks Lewis's vows by gender ("husband and wife",
"wife and husband"...), and falls back to the female wording for anyone
else, which would misgender Sable. So Sable gets the game's own wedding
script (Data/Weddings, exported by museart_export_weddings) with only that
line replaced by gender-neutral vows. Rebuild if a game update changes the
default script.

Usage: build_sable_wedding.py <exports dir> <content pack dir>
"""
import json, os, re, sys
from cp_i18n import Strings

VOWS = ("@... %spouse...#$b#As the mayor of Pelican Town, and regional bearer of the "
        "matrimonial seal, I now pronounce you... married!$h")


def main():
    exports, pack = sys.argv[1], sys.argv[2]
    default = json.load(open(os.path.join(exports, "Data_Weddings.json"), encoding="utf-8"))["EventScript"]["default"]
    gendered = re.compile(r'speak Lewis "\[GenderedText \[SpouseGenderedText .*?\]\]\]\]"')
    strings = Strings(pack, ["wedding."])
    vows = 'speak Lewis "' + strings.add("wedding.vows", VOWS) + '"'
    script, n = gendered.subn(lambda _: vows, default)
    if n != 1:
        sys.exit(f"expected the gendered vows exactly once, found {n}; has the game's wedding changed?")
    # Sable is married in their suit (1.1): dressed once the ceremony's set
    # up in town, and back in everyday clothes as the event ends.
    dress = "changeLocation Town/"
    if script.count(dress) != 1 or script.count("/end wedding") != 1:
        sys.exit("couldn't find where the ceremony starts and ends; has the game's wedding changed?")
    script = script.replace(dress, dress + "changeSprite spouse Wedding/changePortrait spouse Wedding/")
    script = script.replace("/end wedding", "/changeSprite spouse/changePortrait spouse/end wedding")
    changes = {"Changes": [{
        "Action": "EditData",
        "Target": "Data/Weddings",
        "TargetField": ["EventScript"],
        "Entries": {"Sable": script},
    }]}
    header = ("// Sable's wedding: the game's own script with gender-neutral vows, in their suit.\n"
              "// Generated by tools/build_sable_wedding.py; edit that, not this file.\n")
    out = os.path.join(pack, "data", "sable_wedding.json")
    with open(out, "w", encoding="utf-8") as f:
        f.write(header + json.dumps(changes, indent=2, ensure_ascii=False) + "\n")
    strings.save()
    print("wrote", out, "and", strings.path)


if __name__ == "__main__":
    main()
