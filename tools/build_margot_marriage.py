"""Writes Margot Pell's engagement and married lines
([CP] Pelican Palette/data/margot_marriage.json) from the draft in
docs/margot_marriage.md: every "- Key: "line"" there becomes an entry in
Characters/Dialogue/MarriageDialogueMargotPell (keys as the game's: Leah's
and Sable's files are the models). Edit the doc, then rerun this.

The engagement: the bouquet (her dialogue's AcceptBouquet), and the pendant,
which the game answers from Data/EngagementDialogue (<name>0 when she says
yes, <name>1 while you're engaged), as for its own villagers.

Usage: build_margot_marriage.py <content pack dir>
"""
import json, os, re, sys
from cp_i18n import Strings

M = "MargotPell"
DOC = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "docs", "margot_marriage.md")
# Approved in docs/margot_events.md ("Bouquet, pendant and marriage"), and
# the engaged line from docs/margot_marriage.md.
BOUQUET = "Flowers. For me. I'm going to press one and keep it forever and you're not allowed to watch me do it.$l"
PENDANT = "...Yes. Yes! Sorry. Yes.$6#$b#I'm going to need a new card for the museum.$h"
ENGAGED = "I keep writing 'Margot Pell' on things and stopping halfway. Like I've forgotten how it ends.$l"


def married_lines():
    text = open(DOC, encoding="utf-8").read()
    married = text.split("## Married lines", 1)[1]
    lines = re.findall(r'^- (\w+): "(.*)"\s*$', married, flags=re.M)
    if len(lines) < 50:
        sys.exit(f"only {len(lines)} lines found in {DOC}; has its layout changed?")
    return lines


def main():
    pack = sys.argv[1]
    strings = Strings(pack, ["margot.marriage.", "margot.engagement."])
    married = {key: strings.add(f"margot.marriage.{key}", line) for key, line in married_lines()}
    changes = {"Changes": [
        {"Action": "EditData", "Target": f"Characters/Dialogue/{M}",
         "Entries": {"AcceptBouquet": strings.add("margot.engagement.bouquet", BOUQUET)}},
        {"Action": "EditData", "Target": "Data/EngagementDialogue",
         "Entries": {f"{M}0": strings.add("margot.engagement.0", PENDANT),
                     f"{M}1": strings.add("margot.engagement.1", ENGAGED)}},
        {"Action": "Load", "Target": f"Characters/Dialogue/MarriageDialogue{M}", "FromFile": "data/blank.json"},
        {"Action": "EditData", "Target": f"Characters/Dialogue/MarriageDialogue{M}", "Entries": married},
    ]}
    header = ("// Margot's engagement and married lines. Generated by tools/build_margot_marriage.py\n"
              "// from docs/margot_marriage.md: edit the doc, not this file.\n")
    out = os.path.join(pack, "data", "margot_marriage.json")
    with open(out, "w", encoding="utf-8") as f:
        f.write(header + json.dumps(changes, indent=2, ensure_ascii=False) + "\n")
    strings.save()
    print("wrote", out, f"({len(married)} married lines) and", strings.path)


if __name__ == "__main__":
    main()
