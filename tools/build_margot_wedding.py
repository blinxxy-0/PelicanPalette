"""Writes Margot Pell's wedding ([CP] Pelican Palette/data/margot_wedding.json).

The game's own wedding script (Data/Weddings, exported by
museart_export_weddings), with Margot changed into her wedding dress once
the ceremony's set up in town and back into everyday clothes as it ends, as
Sable's is (build_sable_wedding.py). Lewis's vows are the game's own.

The approved draft (docs/margot_events.md): Gunther and Sable in the front
row; Julian, if you've met him, at the back, pretending not to cry. They're
wedding attendees only at her wedding (on the wedding morning you're already
married to her), at free spots beside the game's own guests.

Usage: build_margot_wedding.py <exports dir> <content pack dir>
"""
import json, os, sys

M = "MargotPell"
AT_HER_WEDDING = f"PLAYER_NPC_RELATIONSHIP Current {M} Married"
ATTENDEES = {
    # The front row, at either end.
    "Gunther": dict(Setup="Gunther 22 65 0", Celebration="faceDirection Gunther 1 true"),
    "Sable": dict(Setup="Sable 34 65 0", Celebration="faceDirection Sable 3 true",
                  Condition="PLAYER_HAS_MET Target Sable"),
    # At the back, wiping his eyes (the sad emote) when it's done.
    "JulianVane": dict(Setup="JulianVane 28 70 0", Celebration="emote JulianVane 28 true",
                       Condition="PLAYER_HAS_MET Target JulianVane"),
}


def main():
    exports, pack = sys.argv[1], sys.argv[2]
    script = json.load(open(os.path.join(exports, "Data_Weddings.json"), encoding="utf-8"))["EventScript"]["default"]
    dress = "changeLocation Town/"
    if script.count(dress) != 1 or script.count("/end wedding") != 1:
        sys.exit("couldn't find where the ceremony starts and ends; has the game's wedding changed?")
    script = script.replace(dress, dress + "changeSprite spouse Wedding/changePortrait spouse Wedding/")
    script = script.replace("/end wedding", "/changeSprite spouse/changePortrait spouse/end wedding")
    attendees = {}
    for npc, a in ATTENDEES.items():
        condition = AT_HER_WEDDING + (", " + a["Condition"] if "Condition" in a else "")
        attendees[f"blinxxy.MuseArt_MargotWedding_{npc}"] = {
            "Id": npc, "Condition": condition, "Setup": a["Setup"], "Celebration": a["Celebration"]}
    changes = {"Changes": [
        {"Action": "EditData", "Target": "Data/Weddings", "TargetField": ["EventScript"], "Entries": {M: script}},
        {"Action": "EditData", "Target": "Data/Weddings", "TargetField": ["Attendees"], "Entries": attendees},
    ]}
    header = ("// Margot's wedding: the game's own script, in her wedding dress, with Gunther,\n"
              "// Sable and Julian among the guests. Generated by tools/build_margot_wedding.py;\n"
              "// edit that, not this file.\n")
    out = os.path.join(pack, "data", "margot_wedding.json")
    with open(out, "w", encoding="utf-8") as f:
        f.write(header + json.dumps(changes, indent=2, ensure_ascii=False) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
